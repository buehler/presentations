#!/usr/bin/env python3
"""Write the root index.html with a link to every deck in decks/.

A deck is any folder decks/<name>/ that contains an index.html. Link text is
the folder name; decks are sorted newest first (folder names descending, so
date-prefixed names like 2026-11-16_topic sort by date). The deck's <title>
is shown as a subtitle.

Run from anywhere: python3 scripts/build_index.py
The GitHub Pages workflow runs it on every push, so the published index is
always current; commit the regenerated file to keep the local copy in sync.
"""

import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DECKS = ROOT / "decks"
OUT = ROOT / "index.html"


def deck_title(index: Path) -> str:
    match = re.search(r"<title>(.*?)</title>", index.read_text(encoding="utf-8"), re.S | re.I)
    return html.unescape(match.group(1).strip()) if match else ""


def deck_items() -> str:
    names = sorted(
        (d.name for d in DECKS.iterdir() if d.is_dir() and (d / "index.html").is_file()),
        reverse=True,
    )
    items = []
    for name in names:
        title = deck_title(DECKS / name / "index.html")
        sub = f'\n          <span class="title">{html.escape(title)}</span>' if title else ""
        href = f"decks/{html.escape(name)}/index.html"
        items.append(
            f"""      <li class="deck">
        <a class="open" href="{href}">
          <span class="name">{html.escape(name)}</span>{sub}
        </a>
        <a class="pdf" href="{href}?print-pdf" aria-label="Open {html.escape(name)} in print view to save as PDF">PDF</a>
        <span class="arrow" aria-hidden="true">→</span>
      </li>"""
        )
    return "\n".join(items) if items else '      <li class="empty">No decks yet.</li>'


